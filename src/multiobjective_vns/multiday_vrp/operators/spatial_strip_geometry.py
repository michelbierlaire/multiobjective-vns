from __future__ import annotations

from dataclasses import dataclass
from functools import lru_cache
from math import comb, cos, factorial, floor, isfinite, pi, sin, sqrt

from multiobjective_vns.random_source import RandomSource
from multiobjective_vns.values import require_integer

__all__ = [
    'SpatialDeliveryPoint',
    'SpatialSweepOrder',
    'SpatialSweepPartition',
    'sample_sweep_partitions',
]

type _Point = tuple[str, str, float, float]


@dataclass(frozen=True, slots=True)
class SpatialDeliveryPoint:
    """A package delivery's ID, node ID, and planar coordinates."""

    package_id: str
    node_id: str
    x: float
    y: float


@dataclass(frozen=True, slots=True)
class SpatialSweepOrder:
    """One order generated by a particular configured sweep geometry."""

    package_order: tuple[str, ...]
    orientation_index: int | None
    width_multiplier: float | None
    offset_multiplier: float | None
    reverse: bool


@dataclass(frozen=True, slots=True)
class SpatialSweepPartition:
    """One sweep configuration, route partition, and route assignment."""

    sweep_order: SpatialSweepOrder
    cut_positions: tuple[int, ...]
    route_assignment: tuple[int, ...]

    @property
    def package_order(self) -> tuple[str, ...]:
        """Return the package sequence from the selected sweep geometry."""
        return self.sweep_order.package_order


def sample_sweep_partitions(
    points: tuple[SpatialDeliveryPoint, ...],
    *,
    route_count: int,
    max_alternatives: int,
    random_source: RandomSource,
) -> tuple[SpatialSweepPartition, ...]:
    """Sample complete strip-sweep partitions without replacement.

    Positive-area delivery sets use the configured strip orientations, widths,
    offsets, and directions. Collinear and coincident delivery sets use their
    stable degenerate-geometry orders. Each sampled alternative also has
    nonempty contiguous route blocks and a permutation assigning those blocks
    to the selected route positions.

    :param points: Distinct package delivery points in the selected route group.
    :param route_count: Number of selected vehicle routes receiving blocks.
    :param max_alternatives: Maximum distinct alternatives to sample.
    :param random_source: Search's shared random stream.
    :returns: Distinct sampled sweep, cut, and assignment alternatives.
    :raises TypeError: If points, limits, or random draws have invalid types.
    :raises ValueError: If points are empty or limits are out of range.
    """
    if type(points) is not tuple or any(
        type(point) is not SpatialDeliveryPoint for point in points
    ):
        raise TypeError('points must be a tuple of SpatialDeliveryPoint values')
    route_total = require_integer(route_count, name='route_count', minimum=1)
    alternative_limit = require_integer(
        max_alternatives,
        name='max_alternatives',
        minimum=1,
    )
    if not points:
        raise ValueError('points must not be empty')
    if route_total > len(points):
        raise ValueError('route_count must not exceed the number of delivery points')
    package_ids = tuple(point.package_id for point in points)
    if any(type(package_id) is not str or not package_id for package_id in package_ids):
        raise TypeError('point package IDs must be nonempty strings')
    if len(set(package_ids)) != len(package_ids):
        raise ValueError('delivery package IDs must be unique')
    if any(
        type(value) is not float or not isfinite(value)
        for point in points
        for value in (point.x, point.y)
    ):
        raise TypeError('delivery coordinates must be finite Python floats')

    encoded_points = tuple(
        (point.package_id, point.node_id, point.x, point.y) for point in points
    )
    orders = _sweep_orders(encoded_points)
    cut_count = comb(len(points) - 1, route_total - 1)
    assignment_count = factorial(route_total)
    total = len(orders) * cut_count * assignment_count
    ranks = _sample_integer_ranks(
        total,
        min(alternative_limit, total),
        random_source,
    )
    alternatives: list[SpatialSweepPartition] = []
    for rank in ranks:
        geometry_index, cut_rank, assignment_rank = _decode_rank(
            rank,
            cut_count=cut_count,
            assignment_count=assignment_count,
        )
        alternatives.append(
            SpatialSweepPartition(
                orders[geometry_index],
                _unrank_combination(len(points) - 1, route_total - 1, cut_rank),
                _unrank_permutation(route_total, assignment_rank),
            )
        )
    return tuple(alternatives)


def _sweep_orders(points: tuple[_Point, ...]) -> tuple[SpatialSweepOrder, ...]:
    if len(points) > 2048:
        return _build_sweep_orders(points)
    return _cached_sweep_orders(points)


@lru_cache(maxsize=4)
def _cached_sweep_orders(points: tuple[_Point, ...]) -> tuple[SpatialSweepOrder, ...]:
    return _build_sweep_orders(points)


def _build_sweep_orders(points: tuple[_Point, ...]) -> tuple[SpatialSweepOrder, ...]:
    coordinate_scale = max(
        (max(abs(point[2]), abs(point[3])) for point in points),
        default=0.0,
    )
    if coordinate_scale == 0.0:
        normalized = points
    else:
        normalized = tuple(
            (package_id, node_id, x / coordinate_scale, y / coordinate_scale)
            for package_id, node_id, x, y in points
        )
    hull_area = _convex_hull_area(tuple((point[2], point[3]) for point in normalized))
    if hull_area == 0.0:
        order = _degenerate_order(normalized)
        return (
            SpatialSweepOrder(order, None, None, None, False),
            SpatialSweepOrder(tuple(reversed(order)), None, None, None, True),
        )

    reference_width = sqrt(hull_area / len(points))
    orders: list[SpatialSweepOrder] = []
    for orientation_index in range(8):
        angle = orientation_index * pi / 8.0
        longitudinal_axis = (cos(angle), sin(angle))
        lateral_axis = (-sin(angle), cos(angle))
        projected = tuple(
            (
                package_id,
                node_id,
                x * longitudinal_axis[0] + y * longitudinal_axis[1],
                x * lateral_axis[0] + y * lateral_axis[1],
            )
            for package_id, node_id, x, y in normalized
        )
        minimum_lateral = min(point[3] for point in projected)
        for multiplier in (0.5, 0.75, 1.0, 1.5, 2.0):
            width = reference_width * multiplier
            for offset_multiplier in (0.0, 0.5):
                offset = width * offset_multiplier
                by_strip: dict[int, list[tuple[str, str, float, float]]] = {}
                for point in projected:
                    strip = floor((point[3] - minimum_lateral - offset) / width)
                    by_strip.setdefault(strip, []).append(point)
                for reverse in (False, True):
                    ordered: list[tuple[str, str, float, float]] = []
                    for strip in sorted(by_strip):
                        if strip % 2 == 0:
                            ordered.extend(
                                sorted(
                                    by_strip[strip],
                                    key=lambda point: (point[2], point[1], point[0]),
                                )
                            )
                        else:
                            ordered.extend(
                                sorted(
                                    by_strip[strip],
                                    key=lambda point: (-point[2], point[1], point[0]),
                                )
                            )
                    if reverse:
                        ordered.reverse()
                    orders.append(
                        SpatialSweepOrder(
                            tuple(point[0] for point in ordered),
                            orientation_index,
                            multiplier,
                            offset_multiplier,
                            reverse,
                        )
                    )
    return tuple(orders)


def _convex_hull_area(points: tuple[tuple[float, float], ...]) -> float:
    unique_points = sorted(set(points))
    if len(unique_points) < 3:
        return 0.0

    def cross(
        origin: tuple[float, float],
        first: tuple[float, float],
        second: tuple[float, float],
    ) -> float:
        return (first[0] - origin[0]) * (second[1] - origin[1]) - (
            first[1] - origin[1]
        ) * (second[0] - origin[0])

    lower: list[tuple[float, float]] = []
    for point in unique_points:
        while len(lower) >= 2 and cross(lower[-2], lower[-1], point) <= 0.0:
            lower.pop()
        lower.append(point)
    upper: list[tuple[float, float]] = []
    for point in reversed(unique_points):
        while len(upper) >= 2 and cross(upper[-2], upper[-1], point) <= 0.0:
            upper.pop()
        upper.append(point)
    hull = lower[:-1] + upper[:-1]
    if len(hull) < 3:
        return 0.0
    twice_area = sum(
        first[0] * second[1] - first[1] * second[0]
        for first, second in zip(hull, (*hull[1:], hull[0]), strict=True)
    )
    return abs(twice_area) / 2.0


def _degenerate_order(points: tuple[_Point, ...]) -> tuple[str, ...]:
    if len({(point[2], point[3]) for point in points}) == 1:
        return tuple(
            point[0] for point in sorted(points, key=lambda point: (point[1], point[0]))
        )
    ordered_points = sorted(points, key=lambda point: (point[1], point[0]))
    farthest_pair: tuple[_Point, _Point] | None = None
    farthest_distance = -1.0
    farthest_key: tuple[tuple[str, str], tuple[str, str]] | None = None
    for first_index, first in enumerate(ordered_points):
        for second in ordered_points[first_index + 1 :]:
            distance = (first[2] - second[2]) ** 2 + (first[3] - second[3]) ** 2
            endpoints = sorted(((first[1], first[0]), (second[1], second[0])))
            endpoint_key = (endpoints[0], endpoints[1])
            if distance > farthest_distance or (
                distance == farthest_distance
                and (farthest_key is None or endpoint_key < farthest_key)
            ):
                farthest_pair = (first, second)
                farthest_distance = distance
                farthest_key = endpoint_key
    if farthest_pair is None:
        return tuple(point[0] for point in ordered_points)
    first, second = farthest_pair
    if (second[2], second[3]) < (first[2], first[3]):
        first, second = second, first
    dx = second[2] - first[2]
    dy = second[3] - first[3]
    return tuple(
        point[0]
        for point in sorted(
            points,
            key=lambda point: (
                (point[2] - first[2]) * dx + (point[3] - first[3]) * dy,
                point[1],
                point[0],
            ),
        )
    )


def _sample_integer_ranks(
    population_size: int,
    sample_size: int,
    random_source: RandomSource,
) -> tuple[int, ...]:
    substitutions: dict[int, int] = {}
    selected: list[int] = []
    for position in range(sample_size):
        remaining = population_size - position
        target = position + _random_below(remaining, random_source)
        selected_value = substitutions.get(target, target)
        substitutions[target] = substitutions.get(position, position)
        selected.append(selected_value)
    return tuple(selected)


def _random_below(population_size: int, random_source: RandomSource) -> int:
    if population_size <= 0:
        raise ValueError('population_size must be positive')
    if population_size == 1:
        return 0
    bit_count = population_size.bit_length()
    chunk_count = (bit_count + 52) // 53
    mask = (1 << bit_count) - 1
    while True:
        candidate = 0
        for _ in range(chunk_count):
            draw = random_source.random()
            if type(draw) is not float:
                raise TypeError('RandomSource.random() must return a Python float')
            if not isfinite(draw) or not 0.0 <= draw < 1.0:
                raise ValueError('RandomSource.random() must return a float in [0, 1)')
            candidate = (candidate << 53) | int(draw * (1 << 53))
        candidate &= mask
        if candidate < population_size:
            return candidate


def _decode_rank(
    rank: int,
    *,
    cut_count: int,
    assignment_count: int,
) -> tuple[int, int, int]:
    geometry_index, remainder = divmod(rank, cut_count * assignment_count)
    cut_rank, assignment_rank = divmod(remainder, assignment_count)
    return geometry_index, cut_rank, assignment_rank


def _unrank_combination(
    item_count: int,
    selected_count: int,
    rank: int,
) -> tuple[int, ...]:
    selected: list[int] = []
    next_item = 0
    for selected_position in range(selected_count):
        remaining_selected = selected_count - selected_position - 1
        for item in range(next_item, item_count):
            completions = comb(item_count - item - 1, remaining_selected)
            if rank < completions:
                selected.append(item + 1)
                next_item = item + 1
                break
            rank -= completions
    return tuple(selected)


def _unrank_permutation(size: int, rank: int) -> tuple[int, ...]:
    remaining = list(range(size))
    output: list[int] = []
    for position in range(size):
        block_size = factorial(size - position - 1)
        selected_index, rank = divmod(rank, block_size)
        output.append(remaining.pop(selected_index))
    return tuple(output)
